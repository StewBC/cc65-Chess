/*
 *	c64drive.c
 *	cc65 Chess - test support
 *
 *	What a search node costs on a real C64 with and without the mate drive,
 *	which is the one number doc/strength.md 5.1.6 could not measure.
 *
 *	This file exists because neither instrument already here can price it.
 *	c64search.c runs from the opening position, where gePhase is 6400 against
 *	the term's bound of 1100 - it cannot execute, so that benchmark would
 *	faithfully report zero.  c64evasion.c has the right shape but the wrong
 *	positions: it replays a middlegame, because check evasions cost nothing
 *	where nobody is in check.  The mate drive is the opposite selection
 *	problem and needs an ending.
 *
 *	The fixed-replay trick is c64evasion.c's and the reason is the same: two
 *	builds that pick their own moves diverge at the first disagreement and then
 *	measure different positions, which is not a measurement of anything.  Every
 *	position here is identical in both builds; only the cost of visiting it
 *	differs, and nodes per second is the figure because the two builds do not
 *	visit the same *number* of nodes from the same position.
 *
 *	The game is game 0 of the pre-fix Sargon II baseline - the one that reached
 *	king and rook against a bare king on move 66 and drew by the fifty-move
 *	rule, which is the defect the term was built for.  Searching starts at ply
 *	83, where gePhase first falls to 1100; before that the moves are replayed
 *	without being searched, because timing a middlegame this term cannot enter
 *	only dilutes the answer.  Of the 148 timed plies the term is live in about
 *	two thirds, so the figure below is the cost where it applies rather than
 *	the cost averaged over a whole game - state it that way when quoting it.
 *
 *	Build both halves from the shipping configuration.  The tuning build cannot
 *	be used: EVAL_TUNING makes every node dearer and a node's cost is the thing
 *	being measured.
 *	  cl65 -t c64 -Oris -I../src -o c64drive-on.prg \
 *	       ../src/engine.c ../src/eval.c ../src/search.c c64drive.c
 *	  cl65 -t c64 -Oris -I../src -DEVAL_MATEDRIVE_ON=0 -o c64drive-off.prg \
 *	       ../src/engine.c ../src/eval.c ../src/search.c c64drive.c
 */

